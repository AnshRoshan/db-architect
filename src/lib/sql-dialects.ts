import type { SchemaModel, EntityModel, FieldModel, ConstraintModel } from "./schema-model";
import type { SchemaDiff } from "./diff-migrate";

export type SqlDialect = "postgres" | "mysql" | "sqlite";

export function q(dialect: SqlDialect, name: string): string {
  return dialect === "mysql" ? "`" + name.replace(/`/g, "``") + "`" : '"' + name.replace(/"/g, '""') + '"';
}
export function qcol(dialect: SqlDialect, c: string): string {
  return /^[A-Za-z_][A-Za-z0-9_]*$/.test(c) ? q(dialect, c) : c;
}
export function qualified(dialect: SqlDialect, e: Pick<EntityModel, "namespace" | "shortName">): string {
  return dialect === "postgres" ? `${q(dialect, e.namespace)}.${q(dialect, e.shortName)}` : q(dialect, e.shortName);
}
export function pkColumns(e: EntityModel): string[] {
  const c = e.constraints.find((x) => x.kind === "primary_key");
  if (c && c.columns.length) return c.columns;
  return e.fields.filter((f) => f.isPrimaryKey).map((f) => f.name);
}
function isAuto(f: FieldModel): boolean {
  return Boolean(f.identity) || /serial/i.test(f.type) || /nextval\(|auto_increment/i.test(f.defaultValue ?? "");
}

/** Referenced tables first; cycles are broken deterministically. */
export function topoEntities(model: SchemaModel): EntityModel[] {
  const byName = new Map(model.entities.map((e) => [e.name, e]));
  const out: EntityModel[] = [];
  const state = new Map<string, number>();
  const visit = (e: EntityModel) => {
    if (state.get(e.name)) return;
    state.set(e.name, 1);
    for (const c of e.constraints) {
      if (c.kind === "foreign_key" && c.referencedEntity && c.referencedEntity !== e.name) {
        const dep = byName.get(c.referencedEntity);
        if (dep) visit(dep);
      }
    }
    out.push(e);
  };
  model.entities.forEach(visit);
  return out;
}

function fkClause(c: ConstraintModel, dialect: SqlDialect, model: SchemaModel): string {
  const ref = model.entities.find((x) => x.name === c.referencedEntity);
  const refName = ref ? qualified(dialect, ref) : q(dialect, (c.referencedEntity ?? "").split(".").pop() ?? "");
  let s = `FOREIGN KEY (${c.columns.map((x) => q(dialect, x)).join(", ")}) REFERENCES ${refName} (${(c.referencedColumns?.length ? c.referencedColumns : ["id"]).map((x) => q(dialect, x)).join(", ")})`;
  if (c.onDelete && !/^no action$/i.test(c.onDelete)) s += ` ON DELETE ${c.onDelete}`;
  if (c.onUpdate && !/^no action$/i.test(c.onUpdate)) s += ` ON UPDATE ${c.onUpdate}`;
  return s;
}

export function createTable(e: EntityModel, dialect: SqlDialect, model: SchemaModel, opts: { deferForeignKeys?: boolean } = {}): string {
  const pk = pkColumns(e);
  const lines: string[] = [];
  const inlineSqlitePk = dialect === "sqlite" && pk.length === 1 && isAuto(e.fields.find((f) => f.name === pk[0]) ?? ({} as FieldModel));
  for (const f of e.fields) {
    if (inlineSqlitePk && f.name === pk[0]) { lines.push(`${q(dialect, f.name)} INTEGER PRIMARY KEY AUTOINCREMENT`); continue; }
    let def = `${q(dialect, f.name)} ${f.type}`;
    if (!f.nullable || pk.includes(f.name)) def += " NOT NULL";
    if (isAuto(f)) {
      if (dialect === "postgres" && !/serial/i.test(f.type)) def += " GENERATED BY DEFAULT AS IDENTITY";
      if (dialect === "mysql") def += " AUTO_INCREMENT";
    } else if (f.defaultValue != null && f.defaultValue !== "") def += ` DEFAULT ${f.defaultValue}`;
    lines.push(def);
  }
  if (pk.length && !inlineSqlitePk) {
    const name = e.constraints.find((c) => c.kind === "primary_key")?.name ?? `${e.shortName}_pkey`;
    lines.push(`${dialect === "mysql" ? "" : `CONSTRAINT ${q(dialect, name)} `}PRIMARY KEY (${pk.map((c) => q(dialect, c)).join(", ")})`);
  }
  for (const c of e.constraints.filter((x) => x.kind === "unique")) {
    if (c.columns.join() === pk.join()) continue;
    lines.push(dialect === "mysql" ? `UNIQUE KEY ${q(dialect, c.name)} (${c.columns.map((x) => q(dialect, x)).join(", ")})` : `CONSTRAINT ${q(dialect, c.name)} UNIQUE (${c.columns.map((x) => q(dialect, x)).join(", ")})`);
  }
  for (const c of e.constraints.filter((x) => x.kind === "check" && x.definition)) {
    lines.push(`CONSTRAINT ${q(dialect, c.name)} CHECK (${c.definition})`);
  }
  if (!opts.deferForeignKeys) {
    for (const c of e.constraints.filter((x) => x.kind === "foreign_key")) lines.push(`CONSTRAINT ${q(dialect, c.name)} ${fkClause(c, dialect, model)}`);
  }
  const suffix = dialect === "mysql" ? " ENGINE=InnoDB DEFAULT CHARSET=utf8mb4" : "";
  return `CREATE TABLE ${qualified(dialect, e)} (\n  ${lines.join(",\n  ")}\n)${suffix};`;
}

export function createIndexes(e: EntityModel, dialect: SqlDialect): string[] {
  const out: string[] = [];
  const uniques = new Set(e.constraints.filter((c) => c.kind === "unique" || c.kind === "primary_key").map((c) => c.columns.join()));
  for (const ix of e.indexes) {
    if (!ix.columns.length) continue;
    if (uniques.has(ix.columns.join()) && ix.unique) continue;
    let s = `CREATE ${ix.unique ? "UNIQUE " : ""}INDEX ${q(dialect, ix.name)} ON ${qualified(dialect, e)}`;
    if (dialect === "postgres" && ix.method && ix.method !== "btree") s += ` USING ${ix.method}`;
    s += ` (${ix.columns.map((c) => qcol(dialect, c)).join(", ")})`;
    if (ix.partial && ix.predicate && dialect !== "mysql") s += ` ${ix.predicate.replace(/^\s*WHERE\s+/i, "WHERE ")}`;
    out.push(s + ";");
  }
  return out;
}

export function generateDdl(model: SchemaModel, dialect: SqlDialect, opts: { deferForeignKeys?: boolean } = {}): string {
  const label = { postgres: "PostgreSQL", mysql: "MySQL (InnoDB)", sqlite: "SQLite" }[dialect];
  const ordered = topoEntities(model).filter((e) => e.kind === "table");
  const out: string[] = [`-- DB Architect · target schema (${label})`, `-- Generated ${new Date().toISOString()} — review before applying`, ""];
  const ns = model.namespaces[0];
  if (dialect === "postgres" && ns && ns !== "public") out.push(`CREATE SCHEMA IF NOT EXISTS ${q(dialect, ns)};`, "");
  if (dialect === "mysql" && ns) out.push(`CREATE DATABASE IF NOT EXISTS ${q(dialect, ns)} DEFAULT CHARACTER SET utf8mb4;`, `USE ${q(dialect, ns)};`, "");
  if (dialect === "sqlite") out.push("PRAGMA foreign_keys = ON;", "");
  out.push("-- Phase 1 · tables");
  for (const e of ordered) out.push(createTable(e, dialect, model, opts), "");
  const idx = ordered.flatMap((e) => createIndexes(e, dialect));
  if (idx.length) out.push("-- Phase 1 · indexes", ...idx, "");
  if (opts.deferForeignKeys) {
    out.push("-- Phase 2 · foreign keys — apply AFTER data load and an orphan check");
    for (const e of ordered) {
      for (const c of e.constraints.filter((x) => x.kind === "foreign_key")) {
        out.push(dialect === "sqlite"
          ? `-- SQLite cannot ADD CONSTRAINT: include ${c.name} when creating ${e.shortName}, or rebuild the table`
          : `ALTER TABLE ${qualified(dialect, e)} ADD CONSTRAINT ${q(dialect, c.name)} ${fkClause(c, dialect, model)}${dialect === "postgres" ? " NOT VALID" : ""};`);
        if (dialect === "postgres") out.push(`ALTER TABLE ${qualified(dialect, e)} VALIDATE CONSTRAINT ${q(dialect, c.name)};`);
      }
    }
  }
  return out.join("\n");
}

// ── MySQL / SQLite migration generation ───────────────────────────
export function generateSqlMigration(dialect: "mysql" | "sqlite", diff: SchemaDiff, source: SchemaModel, target: SchemaModel): { up: string; down: string; risks: string[] } {
  const tx = dialect === "sqlite";
  const up: string[] = [`-- DB Architect migration (${dialect})`, `-- Generated: ${new Date().toISOString()}`, `-- Source: ${diff.sourceLabel} → Target: ${diff.targetLabel}`, `-- REVIEW REQUIRED. Destructive data changes remain commented out.`];
  const down: string[] = [`-- DB Architect rollback (best-effort; irreversible steps marked)`];
  if (dialect === "mysql") {
    up.push(`-- NOTE: MySQL DDL implicitly commits — it is NOT transactional. Apply in a maintenance window with a backup.`);
    down.push(`-- NOTE: MySQL DDL implicitly commits.`);
  } else {
    up.push("PRAGMA foreign_keys = ON;", "BEGIN;");
    down.push("BEGIN;");
  }
  up.push("");
  const risks: string[] = [];
  const tMap = new Map(target.entities.map((e) => [e.name, e]));
  const sMap = new Map(source.entities.map((e) => [e.name, e]));
  const T = (name: string) => { const e = tMap.get(name) ?? sMap.get(name); return e ? qualified(dialect, e) : q(dialect, name.split(".").pop() ?? name); };

  for (const c of diff.changes.filter((x) => x.kind === "add_entity")) {
    const e = tMap.get(c.entity);
    if (!e || e.kind !== "table") continue;
    up.push(`-- + table ${c.entity}`, createTable(e, dialect, target), ...createIndexes(e, dialect));
    down.unshift(`DROP TABLE IF EXISTS ${qualified(dialect, e)};`);
  }
  for (const c of diff.changes.filter((x) => x.kind === "add_field")) {
    const f = c.to as FieldModel;
    let def = `${q(dialect, f.name)} ${f.type}${f.nullable ? "" : " NOT NULL"}${f.defaultValue ? ` DEFAULT ${f.defaultValue}` : ""}`;
    if (!f.nullable && !f.defaultValue) {
      risks.push(`ADD NOT NULL column ${c.entity}.${f.name} without a default ${dialect === "sqlite" ? "is rejected by SQLite" : "fails on populated tables"} — add a default or backfill first.`);
      up.push(`-- HIGH RISK: ${c.entity}.${f.name} needs a default/backfill`);
    }
    up.push(`ALTER TABLE ${T(c.entity)} ADD COLUMN ${def};`);
    down.push(`ALTER TABLE ${T(c.entity)} DROP COLUMN ${q(dialect, f.name)}; -- removes values written after rollout`);
    void def;
  }
  for (const c of diff.changes.filter((x) => x.kind === "alter_field")) {
    const to = c.to as FieldModel, from = c.from as FieldModel;
    if (dialect === "mysql") {
      up.push(`ALTER TABLE ${T(c.entity)} MODIFY COLUMN ${q(dialect, to.name)} ${to.type}${to.nullable ? "" : " NOT NULL"}${to.defaultValue ? ` DEFAULT ${to.defaultValue}` : ""};`);
      down.push(`ALTER TABLE ${T(c.entity)} MODIFY COLUMN ${q(dialect, from.name)} ${from.type}${from.nullable ? "" : " NOT NULL"}${from.defaultValue ? ` DEFAULT ${from.defaultValue}` : ""}; -- may lose precision`);
      risks.push(`MODIFY COLUMN ${c.entity}.${to.name} may rebuild the table (check ALGORITHM=INPLACE support) and fail on uncastable values.`);
    } else {
      up.push(`-- MANUAL (SQLite cannot ALTER COLUMN): rebuild ${c.entity}: CREATE new table → INSERT … SELECT → DROP old → RENAME.`);
      risks.push(`${c.entity}.${to.name} change requires a SQLite table rebuild.`);
    }
  }
  for (const c of diff.changes.filter((x) => x.kind === "add_constraint")) {
    const k = c.to as ConstraintModel;
    if (dialect === "sqlite") { up.push(`-- MANUAL (SQLite cannot ADD CONSTRAINT ${k.name}): rebuild ${c.entity} to add it.`); risks.push(`Constraint ${k.name} on ${c.entity} requires a table rebuild in SQLite.`); continue; }
    if (k.kind === "foreign_key") { up.push(`ALTER TABLE ${T(c.entity)} ADD CONSTRAINT ${q(dialect, k.name)} ${fkClause(k, dialect, target)};`); risks.push(`FK ${k.name} validates existing rows and takes metadata locks; check for orphans first.`); down.push(`ALTER TABLE ${T(c.entity)} DROP FOREIGN KEY ${q(dialect, k.name)};`); }
    else if (k.kind === "unique") { up.push(`ALTER TABLE ${T(c.entity)} ADD UNIQUE KEY ${q(dialect, k.name)} (${k.columns.map((x) => q(dialect, x)).join(", ")});`); down.push(`ALTER TABLE ${T(c.entity)} DROP INDEX ${q(dialect, k.name)};`); }
    else if (k.kind === "check") { up.push(`ALTER TABLE ${T(c.entity)} ADD CONSTRAINT ${q(dialect, k.name)} CHECK (${k.definition ?? "TRUE"});`); down.push(`ALTER TABLE ${T(c.entity)} DROP CHECK ${q(dialect, k.name)};`); }
    else if (k.kind === "primary_key") { up.push(`ALTER TABLE ${T(c.entity)} ADD PRIMARY KEY (${k.columns.map((x) => q(dialect, x)).join(", ")});`); down.push(`ALTER TABLE ${T(c.entity)} DROP PRIMARY KEY;`); }
  }
  for (const c of diff.changes.filter((x) => x.kind === "drop_constraint")) {
    const name = c.detail.split(".").pop() ?? "";
    const old = sMap.get(c.entity)?.constraints.find((k) => k.name === name);
    if (dialect === "sqlite") { up.push(`-- MANUAL (SQLite): rebuild ${c.entity} to drop constraint ${name}.`); continue; }
    up.push(`-- REVIEW: removing an integrity rule`);
    up.push(old?.kind === "foreign_key" ? `ALTER TABLE ${T(c.entity)} DROP FOREIGN KEY ${q(dialect, name)};` : old?.kind === "check" ? `ALTER TABLE ${T(c.entity)} DROP CHECK ${q(dialect, name)};` : old?.kind === "primary_key" ? `ALTER TABLE ${T(c.entity)} DROP PRIMARY KEY;` : `ALTER TABLE ${T(c.entity)} DROP INDEX ${q(dialect, name)};`);
    down.push(`-- MANUAL: restore constraint ${name} from the source schema.`);
    risks.push(`${c.detail} removes an integrity rule.`);
  }
  for (const c of diff.changes.filter((x) => x.kind === "add_index")) {
    const ix = c.to as { name: string; columns: string[]; unique: boolean };
    up.push(`CREATE ${ix.unique ? "UNIQUE " : ""}INDEX ${q(dialect, ix.name)} ON ${T(c.entity)} (${ix.columns.map((x) => qcol(dialect, x)).join(", ")})${dialect === "mysql" ? " ALGORITHM=INPLACE LOCK=NONE" : ""};`);
    down.push(dialect === "mysql" ? `DROP INDEX ${q(dialect, ix.name)} ON ${T(c.entity)};` : `DROP INDEX IF EXISTS ${q(dialect, ix.name)};`);
  }
  for (const c of diff.changes.filter((x) => x.kind === "drop_index")) {
    const name = c.detail.replace(/^DROP INDEX\s+/, "");
    up.push(dialect === "mysql" ? `DROP INDEX ${q(dialect, name)} ON ${T(c.entity)};` : `DROP INDEX IF EXISTS ${q(dialect, name)};`);
    const old = sMap.get(c.entity)?.indexes.find((ix) => ix.name === name);
    if (old) down.push(`CREATE ${old.unique ? "UNIQUE " : ""}INDEX ${q(dialect, old.name)} ON ${T(c.entity)} (${old.columns.map((x) => qcol(dialect, x)).join(", ")});`);
    risks.push(`${c.detail} can regress dependent queries; verify workload first.`);
  }
  for (const c of diff.changes.filter((x) => x.kind === "drop_field")) {
    const n = (c.from as FieldModel).name;
    up.push(`-- DESTRUCTIVE (disabled): ${c.detail}; verify backup + application deploy first`, `-- ALTER TABLE ${T(c.entity)} DROP COLUMN ${q(dialect, n)};`);
    risks.push(`DROP COLUMN ${c.entity}.${n} destroys data.`);
    down.push(`-- IRREVERSIBLE without backup: ${c.entity}.${n}`);
  }
  for (const c of diff.changes.filter((x) => x.kind === "drop_entity")) {
    up.push(`-- DESTRUCTIVE (disabled): DROP TABLE ${T(c.entity)}; backup required`, `-- DROP TABLE ${T(c.entity)};`);
    risks.push(`DROP TABLE ${c.entity} destroys all rows.`);
    down.push(`-- IRREVERSIBLE without backup: ${c.entity}`);
  }
  if (tx) { up.push("", "COMMIT;"); down.push("", "COMMIT;"); }
  return { up: up.join("\n"), down: down.join("\n"), risks };
}
