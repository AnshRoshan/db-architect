import { describe, it, expect } from "vitest";
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { detectSqlDialect } from "../src/lib/engines";
import { parseSqlDdl, parseMongoJson } from "../src/lib/dsl";
import { analyzeModel } from "../src/lib/analysis";
import { planTransform, transformRows } from "../src/lib/transform";
import { synthDataset } from "../src/lib/synth";
import { advise, deriveProfile, DEFAULT_PROFILE, migrationHint } from "../src/lib/advisor";
import { diffModels, generateMigration, validateMigration } from "../src/lib/diff-migrate";
import { FIXTURE_ECOMMERCE_SQL, FIXTURE_MYSQL_SQL, FIXTURE_SQLITE_SQL, FIXTURE_MONGO_JSON, FIXTURE_TARGET_SQL } from "../src/lib/fixtures";

const pg = () => parseSqlDdl(FIXTURE_ECOMMERCE_SQL, "shop").model;
const my = () => parseSqlDdl(FIXTURE_MYSQL_SQL, "shop").model;
const lite = () => parseSqlDdl(FIXTURE_SQLITE_SQL, "notes").model;
const mongo = () => parseMongoJson(FIXTURE_MONGO_JSON, "social_demo").model;

describe("dialect detection & parsing", () => {
  it("detects dialects", () => {
    expect(detectSqlDialect(FIXTURE_MYSQL_SQL)).toBe("mysql");
    expect(detectSqlDialect(FIXTURE_SQLITE_SQL)).toBe("sqlite");
    expect(detectSqlDialect(FIXTURE_ECOMMERCE_SQL)).toBe("postgres");
  });
  it("captures trailing DEFAULT values (regression)", () => {
    const m = pg();
    const status = m.entities.find((e) => e.shortName === "orders")!.fields.find((f) => f.name === "status")!;
    expect(status.defaultValue).toBe("'pending'");
  });
  it("parses a MySQL dump", () => {
    const m = my();
    expect(m.engine).toBe("mysql");
    expect(m.namespaces).toEqual(["shop"]);
    expect(m.entities.map((e) => e.shortName).sort()).toEqual(["customers", "order_items", "orders"]);
    const orders = m.entities.find((e) => e.shortName === "orders")!;
    expect(orders.name).toBe("shop.orders");
    expect(orders.indexes.map((i) => i.name)).toContain("idx_orders_customer");
    expect(orders.constraints.some((c) => c.kind === "foreign_key" && c.referencedEntity === "shop.customers" && c.onDelete === "CASCADE")).toBe(true);
    const cust = m.entities.find((e) => e.shortName === "customers")!;
    expect(cust.fields.find((f) => f.name === "id")!.type).toBe("int unsigned");
    expect(cust.fields.find((f) => f.name === "id")!.identity).toBeTruthy();
    expect(cust.fields.find((f) => f.name === "created_at")!.type).toBe("timestamp");
    expect(cust.constraints.some((c) => c.kind === "unique" && c.columns[0] === "email")).toBe(true);
    expect(m.entities.find((e) => e.shortName === "order_items")!.metadata.storageEngine).toBe("MyISAM");
    expect(m.relationships.length).toBe(2);
    expect(m.warnings.some((w) => /INSERT/.test(w))).toBe(true);
  });
  it("parses a SQLite dump", () => {
    const m = lite();
    expect(m.engine).toBe("sqlite");
    const notes = m.entities.find((e) => e.shortName === "notes")!;
    expect(notes.fields.find((f) => f.name === "id")!.identity).toBeTruthy();
    expect(notes.fields.find((f) => f.name === "created_at")!.type).toBe("datetime");
    expect(m.entities.find((e) => e.shortName === "note_tags")!.constraints.filter((c) => c.kind === "foreign_key").length).toBe(2);
  });
});

describe("analysis", () => {
  it("applies MySQL rules and relabels shared rules", () => {
    const { findings } = analyzeModel(my());
    const ids = findings.map((f) => f.ruleId);
    expect(ids).toContain("MY-ENGINE-001");
    expect(ids).toContain("MY-CHARSET-001");
    expect(ids).toContain("MY-TYPE-020"); // float money
    expect(ids.some((i) => i.startsWith("PG-"))).toBe(false);
  });
  it("applies SQLite rules", () => {
    expect(analyzeModel(lite()).findings.map((f) => f.ruleId)).toContain("SQLITE-FK-001");
  });
});

describe("transform: relational → relational", () => {
  it("PostgreSQL → MySQL", () => {
    const plan = planTransform(pg(), "mysql");
    expect(plan.ddl).toContain("ENGINE=InnoDB");
    expect(plan.ddl).toContain("char(36)");
    expect(plan.ddl).toContain("CREATE DATABASE IF NOT EXISTS");
    expect(plan.mappings.some((m) => m.sourceType === "timestamptz" && m.targetType === "datetime(6)" && m.lossy)).toBe(true);
    expect(plan.ddl.indexOf("`users`")).toBeLessThan(plan.ddl.indexOf("`orders`"));
  });
  it("MySQL → PostgreSQL converts values", () => {
    const plan = planTransform(my(), "postgres");
    expect(plan.ddl).toContain("GENERATED BY DEFAULT AS IDENTITY");
    expect(plan.mappings.find((m) => m.sourceField === "is_active")!.targetType).toBe("boolean");
    const out = transformRows(plan, { "shop.customers": [{ id: 1, email: "a@x.com", full_name: "A", is_active: 1, created_at: "2024-01-01" }] });
    expect(out["public.customers"][0].is_active).toBe(true);
  });
  it("PostgreSQL → SQLite maps booleans and timestamps", () => {
    const plan = planTransform(pg(), "sqlite");
    expect(plan.ddl).toContain("PRAGMA foreign_keys = ON");
    expect(plan.risks.join(" ")).toMatch(/PRAGMA foreign_keys/);
  });
  it("rejects same-engine transforms", () => {
    expect(() => planTransform(pg(), "postgres")).toThrow(/same-engine|both/i);
  });
});

describe("transform: SQL → MongoDB", () => {
  it("embeds owned children and previews documents", () => {
    const model = my();
    const plan = planTransform(model, "mongodb");
    const orders = plan.targetModel.entities.find((e) => e.name === "orders")!;
    expect(orders.fields.some((f) => f.name === "orderItems" && f.isArray)).toBe(true);
    expect(plan.targetModel.entities.some((e) => e.name === "order_items")).toBe(false);
    expect(plan.decisions.some((d) => d.kind === "embed")).toBe(true);
    const out = transformRows(plan, synthDataset(model, plan.sourceTables, 3));
    expect(Object.keys(out).sort()).toEqual(["customers", "orders"]);
    expect(Object.keys(out.orders[0])[0]).toBe("_id");
    expect(out.orders.some((d) => Array.isArray(d.orderItems) && (d.orderItems as unknown[]).length > 0)).toBe(true);
    expect(plan.ddl).toContain("$jsonSchema");
  });
  it("does not embed append-only tables and handles junctions", () => {
    const plan = planTransform(lite(), "mongodb");
    expect(plan.targetModel.entities.some((e) => e.name === "note_tags")).toBe(false);
    expect(plan.targetModel.entities.find((e) => e.name === "notes")!.fields.some((f) => f.name === "tagIds")).toBe(true);
  });
  it("honours embed=none", () => {
    const plan = planTransform(my(), "mongodb", { embed: "none" });
    expect(plan.targetModel.entities.length).toBe(3);
  });
});

describe("transform: MongoDB → SQL", () => {
  it("creates child tables and deferred foreign keys", () => {
    const model = mongo();
    const plan = planTransform(model, "postgres");
    const names = plan.targetModel.entities.map((e) => e.shortName);
    expect(names).toContain("posts");
    expect(names.some((n) => n.startsWith("posts_"))).toBe(true);
    expect(plan.ddl).toContain("Phase 2");
    expect(plan.ddl).toContain("ADD CONSTRAINT");
    const out = transformRows(plan, synthDataset(model, plan.sourceTables, 3));
    expect(out["public.posts"].length).toBe(3);
    expect(String(out["public.posts"][0].id)).toHaveLength(24);
  });
  it("supports MySQL and SQLite targets", () => {
    for (const t of ["mysql", "sqlite"] as const) expect(planTransform(mongo(), t).ddl).toContain("CREATE TABLE");
  });
});

describe("generated ETL scripts are valid JavaScript", () => {
  const dir = mkdtempSync(join(tmpdir(), "etl-"));
  const cases: [string, () => ReturnType<typeof pg>, "postgres" | "mysql" | "sqlite" | "mongodb"][] = [
    ["pg-mysql", pg, "mysql"], ["pg-sqlite", pg, "sqlite"], ["pg-mongo", pg, "mongodb"], ["mysql-mongo", my, "mongodb"],
    ["mongo-pg", mongo, "postgres"], ["mongo-mysql", mongo, "mysql"], ["mongo-sqlite", mongo, "sqlite"], ["sqlite-pg", lite, "postgres"],
  ];
  for (const [name, src, dst] of cases) {
    it(name, () => {
      const file = join(dir, `${name}.cjs`);
      writeFileSync(file, planTransform(src(), dst).etlScript);
      expect(() => execFileSync(process.execPath, ["--check", file], { stdio: "pipe" })).not.toThrow();
    });
  }
});

describe("advisor", () => {
  it("recommends SQLite for embedded/offline", () => {
    const r = advise({ ...DEFAULT_PROFILE, deployment: "embedded", scale: "small", needs: ["offline"] });
    expect(r.ranked[0].id).toBe("sqlite");
  });
  it("recommends ClickHouse for massive analytics", () => {
    const r = advise({ ...DEFAULT_PROFILE, dataShape: "analytics", consistency: "eventual", scale: "massive", queries: "aggregations", writes: "write_heavy", needs: ["analytics_sql"] });
    expect(r.ranked[0].id).toBe("clickhouse");
  });
  it("recommends MongoDB for evolving documents at scale", () => {
    const r = advise({ ...DEFAULT_PROFILE, dataShape: "document", consistency: "eventual", schema: "evolving", scale: "large", needs: ["json"] });
    expect(r.ranked[0].id).toBe("mongodb");
  });
  it("recommends a relational engine for transactional joins", () => {
    const r = advise({ ...DEFAULT_PROFILE, queries: "joins", needs: ["transactions"] });
    expect(["postgres", "mysql", "sqlserver"]).toContain(r.ranked[0].id);
  });
  it("penalizes proprietary engines when open source only", () => {
    const base = advise({ ...DEFAULT_PROFILE, queries: "joins" }).ranked.find((x) => x.id === "sqlserver")!.score;
    const oss = advise({ ...DEFAULT_PROFILE, queries: "joins", stack: "open_source_only" }).ranked.find((x) => x.id === "sqlserver")!.score;
    expect(oss).toBeLessThan(base);
  });
  it("suggests a polyglot search index", () => {
    const r = advise({ ...DEFAULT_PROFILE, queries: "full_text", needs: ["full_text"], dataShape: "relational" });
    expect(r.ranked.length).toBe(10);
  });
  it("derives a profile from a scanned schema", () => {
    const d = deriveProfile(mongo());
    expect(d.profile.dataShape).toBe("document");
    expect(d.signals.length).toBeGreaterThan(0);
    expect(migrationHint("postgres", "mongodb").supported).toBe(true);
    expect(migrationHint("postgres", "dynamodb").supported).toBe(false);
  });
});

describe("migrations", () => {
  it("PostgreSQL keeps CONCURRENTLY outside the transaction", () => {
    const a = pg(), b = parseSqlDdl(FIXTURE_TARGET_SQL, "shop").model;
    const gen = generateMigration("postgres", diffModels(a, b), a, b);
    const tx = gen.up.match(/BEGIN;([\s\S]*?)COMMIT;/)![1];
    expect(tx).not.toMatch(/CONCURRENTLY/);
    expect(gen.up).toMatch(/CONCURRENTLY/);
    expect(validateMigration(gen.up, "postgres").ok).toBe(true);
  });
  it("MySQL migrations are non-transactional and use MODIFY COLUMN", () => {
    const a = my();
    const b = parseSqlDdl(FIXTURE_MYSQL_SQL.replace("`qty` int NOT NULL", "`qty` bigint NOT NULL").replace("KEY `idx_items_order` (`order_id`),", ""), "shop").model;
    const gen = generateMigration("mysql", diffModels(a, b), a, b);
    expect(gen.up).not.toMatch(/\bBEGIN;/);
    expect(gen.up).toMatch(/MODIFY COLUMN `qty` bigint/);
    expect(gen.up).toMatch(/DROP INDEX `idx_items_order`/);
    expect(validateMigration(gen.up, "mysql").ok).toBe(true);
  });
});
